export function halachaForHDate(hd) {
  const desc = descriptionsCached(hd);
  for (const item of OCCASIONS) {
    if (item.when(hd, desc)) {
      return { id: item.id, title: item.title, body: item.body, source: item.source };
    }
  }
  const daily = EVERYDAY[hd.getDate()];
  return { id: "day-" + hd.getDate(), title: daily.title, body: daily.body, source: daily.source };
}

function descriptionsCached(hd) {
  return descriptions(hd);
}

export function occasionTitles() {
  return OCCASIONS.map((item) => ({ id: item.id, title: item.title, source: item.source }));
}
