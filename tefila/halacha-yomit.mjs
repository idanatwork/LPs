function eventsOn(hd) {
  return HebrewCalendar.calendar({ start: hd, end: hd, il: true, omer: true });
}

function descriptions(hd) {
  return eventsOn(hd).map((event) => event.getDesc());
}

function has(desc, re) {
  return desc.some((line) => re.test(line));
}

const PARSHIYOT = [
  ["Shabbat Shekalim", "par-shekalim"],
  ["Shabbat Zachor", "par-zachor"],
  ["Shabbat Parah", "par-parah"],
  ["Shabbat HaChodesh", "par-hachodesh"],
];

function parshaWithin(hd, days) {
  let cursor = hd;
  for (let i = 0; i <= days; i++) {
    const desc = descriptions(cursor);
    for (const [name, id] of PARSHIYOT) {
      if (desc.includes(name)) return id;
    }
    cursor = new HDate(cursor.abs() + 1);
  }
  return "";
}

